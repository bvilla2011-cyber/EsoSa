export function gradeEnglishWriting(text, kind) {
  const original=String(text||'').trim();
  const words=original.match(/[A-Za-z]+(?:['’-][A-Za-z]+)*/g)||[];
  const wordCount=words.length;
  const lower=original.toLowerCase();
  const paragraphs=original.split(/\n\s*\n|\n/).map(x=>x.trim()).filter(Boolean);
  const feedback=[];
  const corrections=[];
  const addCorrection=(pattern,replacement,label)=>{if(pattern.test(original)){corrections.push({found:original.match(pattern)?.[0]||'',suggestion:replacement,label});}};
  addCorrection(/\bin the other hand\b/i,'on the other hand','Connector');
  addCorrection(/\bI am agree\b/i,'I agree','Grammar');
  addCorrection(/\bpeople is\b/i,'people are','Subject–verb agreement');
  addCorrection(/\bmore easier\b/i,'easier','Comparative');
  addCorrection(/\bdiscuss about\b/i,'discuss','Verb pattern');
  addCorrection(/\bdepends of\b/i,'depends on','Preposition');
  addCorrection(/\binformations\b/i,'information','Uncountable noun');
  addCorrection(/\badvices\b/i,'advice','Uncountable noun');
  let score=0;
  const essay=kind==='essay';
  const min=essay?120:80,max=essay?180:150;
  if(wordCount>=min&&wordCount<=max)score+=2;
  else if(wordCount>=min*.7&&wordCount<min){score+=1;feedback.push('Amplía el texto para acercarte al objetivo de '+min+'–'+max+' palabras.');}
  else if(wordCount>max&&wordCount<=max*1.3){score+=1.5;feedback.push('Reduce un poco el texto para respetar la extensión recomendada.');}
  else feedback.push('Ajusta la extensión: objetivo '+min+'–'+max+' palabras; has escrito '+wordCount+'.');
  if(essay){
    const intro=/\b(in this essay|nowadays|these days|many people believe|there is a debate)\b/i.test(lower);
    const conclusion=/\b(to conclude|in conclusion|to sum up|overall|all in all)\b/i.test(lower);
    score+=(intro?.5:0)+(conclusion?.5:0);
    if(!intro)feedback.push('Añade una introducción que presente el tema.');
    if(!conclusion)feedback.push('Cierra con una conclusión (por ejemplo, “To conclude,”).');
    score+=Math.min(1,Math.max(0,paragraphs.length-1)*.25);
    if(paragraphs.length<4)feedback.push('Separa el texto en cuatro párrafos: introducción, argumentos a favor, argumentos en contra y conclusión.');
    const forTerms=/\b(on the one hand|one advantage|advantages|benefit|benefits|supporters|firstly|in favour)\b/i.test(lower);
    const againstTerms=/\b(on the other hand|however|one disadvantage|disadvantages|drawback|drawbacks|opponents|in contrast|against)\b/i.test(lower);
    score+=(forTerms?1.5:0)+(againstTerms?1.5:0);
    if(!forTerms)feedback.push('Desarrolla al menos un argumento a favor y explícalo.');
    if(!againstTerms)feedback.push('Desarrolla al menos un argumento en contra y explícalo.');
    const unitTerms=(lower.match(/\b(might|must|can.t|would|wish|if only|technology|on the cutting edge|light-bulb moment)\b/g)||[]);
    const unitLanguage=new Set(unitTerms).size>=2;
    score+=unitLanguage?1:0;
    if(!unitLanguage)feedback.push('Intenta integrar vocabulario o gramática de las Units 7–8, por ejemplo un modal de especulación o un conector.');
  }else{
    const greeting=/^(hi|hello|dear)\b/i.test(original);
    const signoff=/\b(see you|best|take care|love|write back)\b/i.test(lower);
    const informal=/\b(I’m|i'm|don’t|don't|can’t|can't|we’re|we're|it’s|it's)\b/i.test(original);
    score+=(greeting?1:0)+(signoff?1:0)+(informal?0.5:0);
    if(!greeting)feedback.push('Empieza con un saludo informal, como “Hi Alex,”.');
    if(!signoff)feedback.push('Añade una despedida amistosa y tu nombre.');
    if(!informal)feedback.push('Usa un tono cercano; una contracción como “I’m” o “don’t” encaja bien.');
    score+=Math.min(2,Math.max(0,paragraphs.length-1)*.7);
    if(paragraphs.length<3)feedback.push('Organiza el email en párrafos breves y responde a todos los puntos del tema.');
    score+=/\b(also|because|but|so|and|by the way)\b/i.test(lower)?1:0;
    const emailSentenceCount=(original.match(/[.!?]+/g)||[]).length;
    const emailDetails=emailSentenceCount>=5&&/\b(you|your)\b/i.test(lower)&&/\?/.test(original);
    score+=emailDetails?1.5:.5;
    if(!emailDetails)feedback.push('Desarrolla los detalles del tema y termina preguntando algo a tu amigo o amiga.');
  }
  const connectors=(lower.match(/\b(firstly|secondly|moreover|furthermore|however|although|because|therefore|for example|also|on the other hand|on the one hand)\b/g)||[]);
  score+=Math.min(1, new Set(connectors).size*.25);
  const sentenceStarts=original.split(/[.!?]+/).map(s=>s.trim()).filter(Boolean);
  const capitals=sentenceStarts.filter(s=>/^[A-Z]/.test(s)).length;
  const punctuation=sentenceStarts.length>0&&/[.!?]$/.test(original);
  const grammarScore=(sentenceStarts.length?capitals/sentenceStarts.length:0)+(punctuation?1:0);
  score+=Math.min(1,grammarScore*.5);
  if(capitals<sentenceStarts.length)feedback.push('Revisa las mayúsculas al inicio de cada frase.');
  if(!punctuation)feedback.push('Revisa la puntuación final de las frases.');
  if(corrections.length)feedback.push('Hay algunas construcciones que puedes corregir; revisa las sugerencias.');
  if(!feedback.length)feedback.push('Buen trabajo: revisa igualmente que cada argumento esté explicado con claridad.');
  return {grade:Math.max(0,Math.min(10,Math.round(score*10)/10)),wordCount,paragraphs:paragraphs.length,feedback,corrections};
}
